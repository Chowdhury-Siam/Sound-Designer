import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");

const browser = await chromium.launch({headless: true, ...(process.env.CHROME_PATH ? {executablePath: process.env.CHROME_PATH} : {})});
try {
  const page = await browser.newPage({viewport: {width: 700, height: 800}});
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.addInitScript(() => {
    window.__auditions = [];
    const OriginalAudio = window.Audio;
    window.Audio = class extends OriginalAudio { constructor(...args) { super(...args); window.__auditions.push(this); } };
  });
  await page.goto("http://127.0.0.1:3000/main/");
  assert.equal(await page.locator(".preview-pane").evaluate(e => getComputedStyle(e).display), "none");
  await page.goto("http://127.0.0.1:3000/main/?demo");
  await page.getByRole("button", {name: "Keep library sidebar visible"}).click();
  await page.setViewportSize({width: 400, height: 750});
  assert.equal(await page.locator(".library-panel").evaluate(e => getComputedStyle(e).position), "relative");
  const slider = page.getByRole("slider", {name: "Library panel width"});
  await slider.focus(); await slider.press("ArrowLeft");
  const width = await slider.getAttribute("aria-valuenow");
  await page.reload();
  assert.equal(await slider.getAttribute("aria-valuenow"), width);
  assert.match(await page.locator(".app-shell").getAttribute("class"), /sidebar-pinned/);
  await page.setViewportSize({width: 700, height: 800});
  await page.getByRole("button", {name: "Switch to waveform grid"}).click();
  assert.match(await page.locator(".results-list").getAttribute("class"), /is-grid/);
  await page.getByRole("button", {name: "Browse options", exact: true}).click();
  await page.getByRole("button", {name: "Enable hover audition (350 ms delay)", exact: true}).click();
  await page.keyboard.press("Escape");
  await page.locator(".sound-row").hover();
  await page.waitForTimeout(600);
  assert.ok(await page.evaluate(() => window.__auditions.some(audio => !audio.paused)), "Hover should audition one sound");
  assert.equal(await page.evaluate(() => window.__auditions.filter(audio => !audio.paused).length), 1);
  await page.mouse.move(690, 50);
  await page.waitForTimeout(100);
  assert.equal(await page.evaluate(() => window.__auditions.filter(audio => !audio.paused).length), 0, "Pointer leave must stop audition");
  await page.getByRole("button", {name: "Browse options", exact: true}).click();
  await page.getByRole("button", {name: "Disable hover audition", exact: true}).click();
  await page.keyboard.press("Escape");
  await page.getByRole("button", {name: "Add to favorites", exact: true}).click();
  await page.getByLabel("New favorite subfolder").fill("Whoosh");
  await page.getByRole("button", {name: "Create inside selected destination"}).click();
  await page.getByLabel("New favorite subfolder").fill("Soft");
  await page.getByRole("button", {name: "Create inside selected destination"}).click();
  await page.getByRole("button", {name: "Add favorite", exact: true}).click();
  await page.getByRole("button", {name: "Expand Favorites collections"}).click();
  await page.getByRole("button", {name: "Expand Whoosh collection"}).click();
  assert.equal(await page.locator(".favorite-library-row", {hasText: "Soft"}).count(), 1);
  await page.getByRole("button", {name: "Audio effects", exact: true}).click();
  await page.getByRole("button", {name: "Normalize −1 dB"}).click();
  await page.getByLabel("Echo amount").fill("0.2");
  await page.waitForTimeout(400);
  await page.getByRole("button", {name: "Bypass", exact: true}).click();
  assert.equal(await page.getByRole("button", {name: "Enable FX"}).getAttribute("aria-pressed"), "true");
  if (process.env.SCREENSHOT_PATH) await page.screenshot({path: process.env.SCREENSHOT_PATH});
  await page.getByRole("button", {name: "Close preview and return to browsing"}).click();
  assert.equal(await page.locator(".preview-pane").evaluate(e => getComputedStyle(e).display), "none");
  await page.reload();
  assert.match(await page.locator(".results-list").getAttribute("class"), /is-grid/);
  await page.getByRole("button", {name: "Expand Favorites collections"}).click();
  await page.getByRole("button", {name: "Expand Whoosh collection"}).click();
  assert.equal(await page.locator(".favorite-library-row", {hasText: "Soft"}).count(), 1);
  assert.deepEqual(errors, []);
  console.log("Browser checks passed: pinned narrow resize/reload, grid, nested collection creation, FX/bypass, preview close.");
} finally { await browser.close(); }
